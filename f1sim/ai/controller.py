"""
f1sim/ai/controller.py
======================
Pure-pursuit AI vehicle controller integrating `AIDriverProfile`,
`DifficultyCalibration`, `RacingLineProfile`, OBB/TTC collision avoidance,
DRS slipstream overtaking, and multi-car GP race simulation.
"""
from __future__ import annotations
from collections import deque
from dataclasses import dataclass, field
import math
from typing import Any, Dict, List, Optional, Tuple
import numpy as np

from f1sim.ai.collision import (
    OBB2D,
    OVERTAKE_LATERAL_OFFSET_M,
    TTC_AVOIDANCE_THRESHOLD_S,
    VEHICLE_OBB_LENGTH_M,
    VEHICLE_OBB_WIDTH_M,
    compute_overtake_and_avoidance,
    compute_slipstream_drag_multiplier,
)
from f1sim.ai.driver_profiles import (
    AI_DRIVER_ROSTER,
    AIDifficulty,
    AIDriverProfile,
    DifficultyCalibration,
    estimate_monza_ai_lap_time,
    get_difficulty_calibration,
)
from f1sim.ai.racing_line import (
    RacingLineProfile,
    compute_lookahead_distance,
)
from f1sim.core.constants import RPM_AUTO_UPSHIFT, WHEELBASE
from f1sim.physics.vehicle import Vehicle


@dataclass
class AICarControlOutput:
    """Control commands generated by `AIDriverController` for one simulation step."""
    throttle: float = 0.0
    brake: float = 0.0
    steer_rad: float = 0.0
    drs_active: bool = False
    target_speed_ms: float = 0.0
    lookahead_m: float = 8.0
    ttc_sec: float = float("inf")
    lateral_target_m: float = 0.0


class AIDriverController:
    """
    Autonomous F1 AI driver combining pure-pursuit steering, curvature-based
    speed profiling, TTC collision avoidance, and DRS overtaking.
    """

    def __init__(
        self,
        driver: AIDriverProfile,
        track: Any,
        difficulty: str | AIDifficulty = AIDifficulty.HARD,
        vehicle: Optional[Vehicle] = None,
        racing_line: Optional[RacingLineProfile] = None,
        initial_s: float = 0.0,
        initial_d: float = 0.0,
    ) -> None:
        self.driver: AIDriverProfile = driver
        self.track: Any = track
        self.calibration: DifficultyCalibration = get_difficulty_calibration(difficulty)
        self.vehicle: Vehicle = vehicle if vehicle is not None else Vehicle()
        self.racing_line: RacingLineProfile = (
            racing_line
            if racing_line is not None
            else RacingLineProfile(track, difficulty=self.calibration.name)
        )

        self.s: float = float(initial_s)
        self.d: float = float(initial_d)
        self.heading_error_rad: float = 0.0
        self.lap: int = 1
        self.lap_times: List[float] = []
        self.current_lap_start_time: float = 0.0
        self.total_distance_m: float = float(initial_s)
        self.finished: bool = False
        self.total_race_time: float = 0.0
        self.last_output: AICarControlOutput = AICarControlOutput()

        # Command delay queue for authentic human reaction latency
        self.command_queue: deque = deque()
        self.applied_steer: float = 0.0
        self.applied_throttle: float = 0.0
        self.applied_brake: float = 0.0

        # Synchronize initial 3D pose from track spline if available
        if self.track is not None and hasattr(self.track, "get_spline_point"):
            try:
                pos, tan, norm = self.track.get_spline_point(self.s)
                yaw = self.track.spline.get_heading(self.s) if hasattr(self.track, "spline") else math.atan2(float(tan[1]), float(tan[0]))
                self.vehicle.state.x = float(pos[0] + self.d * norm[0])
                self.vehicle.state.y = float(pos[1] + self.d * norm[1])
                self.vehicle.state.z = float(pos[2])
                self.vehicle.state.yaw = float(yaw)
            except Exception:
                pass

    def get_obb(self, world_x: float | None = None, world_y: float | None = None, heading_rad: float | None = None) -> OBB2D:
        """Returns the 5.63m x 2.00m 2D Oriented Bounding Box for this AI car."""
        wx = float(self.vehicle.state.x) if world_x is None else float(world_x)
        wy = float(self.vehicle.state.y) if world_y is None else float(world_y)
        hr = float(self.vehicle.state.yaw) if heading_rad is None else float(heading_rad)
        return OBB2D(
            center_x=wx,
            center_y=wy,
            heading_rad=hr,
            length=VEHICLE_OBB_LENGTH_M,
            width=VEHICLE_OBB_WIDTH_M,
        )

    def compute_pure_pursuit_steer(
        self,
        speed_ms: float,
        lateral_error_m: float,
        heading_error_rad: float = 0.0,
    ) -> Tuple[float, float]:
        """
        Computes pure-pursuit steering angle (rad) and lookahead distance L_d (m):
            L_d = clamp(8.0 + 0.38 * v, 8.0, 45.0)
            alpha = atan2(-lateral_error, L_d) - heading_error
            delta = atan2(2 * L * sin(alpha), L_d)
        """
        ld = compute_lookahead_distance(speed_ms)
        alpha = math.atan2(-float(lateral_error_m), ld) - float(heading_error_rad)
        steer = math.atan2(2.0 * WHEELBASE * math.sin(alpha), ld)
        steer_clamped = max(-self.vehicle.cfg.max_steer_rad, min(self.vehicle.cfg.max_steer_rad, steer))
        return (float(steer_clamped), float(ld))

    def step(
        self,
        dt: float,
        sim_time: float = 0.0,
        lead_gap_m: Optional[float] = None,
        lead_speed_ms: Optional[float] = None,
        lead_d_m: float = 0.0,
        total_laps: int = 3,
    ) -> AICarControlOutput:
        """
        Executes one AI control and physics step of duration `dt`.
        """
        track_len = float(getattr(self.track, "length", 5793.0))
        s_mod = max(0.0, self.s) % track_len

        # 0. Apply aerodynamic slipstream factor from lead car
        if lead_gap_m is not None and lead_speed_ms is not None and 0.0 < lead_gap_m < 45.0:
            drag_mult = compute_slipstream_drag_multiplier(lead_gap_m, self.d - lead_d_m)
            self.vehicle.aero.set_slipstream_factors(drag_scalar=drag_mult)
        else:
            self.vehicle.aero.set_slipstream_factors(drag_scalar=1.0)

        # 1. Target speed from RacingLineProfile + driver pace_scalar
        v_target = self.racing_line.get_target_speed_ms(s_mod, pace_scalar=self.driver.pace_scalar)

        # 2. Collision avoidance & overtaking offset via TTC
        ttc_sec = float("inf")
        lateral_target = 0.0
        avoid_brake = 0.0
        if lead_gap_m is not None and lead_speed_ms is not None and 0.0 < lead_gap_m < 45.0:
            ttc_sec, lateral_target, avoid_brake = compute_overtake_and_avoidance(
                distance_m=lead_gap_m,
                v_follower_ms=self.vehicle.vx,
                v_leader_ms=lead_speed_ms,
                leader_d_m=lead_d_m,
                ttc_threshold_s=TTC_AVOIDANCE_THRESHOLD_S,
            )

        # 3. Pure-pursuit lateral tracking with subtle driver error variance
        err_offset = float(getattr(self.driver, "error_rate", 0.02)) * (
            1.5 * math.sin(0.47 * sim_time) + 0.8 * math.cos(1.13 * sim_time)
        )
        lat_error = self.d - (lateral_target + err_offset)
        steer_rad, ld = self.compute_pure_pursuit_steer(
            speed_ms=self.vehicle.vx,
            lateral_error_m=lat_error,
            heading_error_rad=self.heading_error_rad,
        )

        # 4. Longitudinal throttle / brake control
        v_curr = self.vehicle.vx
        v_err = v_target - v_curr
        if avoid_brake > 0.01:
            raw_throttle = 0.0
            raw_brake = max(avoid_brake, min(1.0, -v_err / 12.0))
        elif v_err >= 0.5:
            raw_throttle = min(self.calibration.throttle_exit_cap, 0.35 + 0.25 * v_err)
            raw_brake = 0.0
            # Corner traction taper: scale throttle if high steering angle to prevent wheelspin
            if abs(steer_rad) > 0.25:
                raw_throttle = min(raw_throttle, 0.35)
        elif v_err <= -2.0:
            raw_throttle = 0.0
            raw_brake = min(1.0, abs(v_err) / 18.0)
        else:
            raw_throttle = max(0.0, min(self.calibration.throttle_exit_cap, 0.25 + 0.15 * v_err))
            raw_brake = 0.0

        # Enforce reaction latency via FIFO timestamped queue
        latency = self.calibration.reaction_latency_s
        if latency > 1e-4:
            self.command_queue.append((sim_time + latency, raw_throttle, raw_brake, steer_rad))
            while self.command_queue and self.command_queue[0][0] <= sim_time:
                _, self.applied_throttle, self.applied_brake, self.applied_steer = self.command_queue.popleft()
            if len(self.command_queue) == 1 and sim_time <= latency:
                self.applied_throttle = raw_throttle
                self.applied_brake = raw_brake
                self.applied_steer = steer_rad
            cmd_throttle = self.applied_throttle
            cmd_brake = self.applied_brake
            target_steer = self.applied_steer
        else:
            cmd_throttle = raw_throttle
            cmd_brake = raw_brake
            target_steer = steer_rad

        # Continuous steering slew rate limiter (max 6.0 rad/s)
        max_steer_delta = 6.0 * dt
        d_steer = max(-max_steer_delta, min(max_steer_delta, target_steer - self.vehicle.state.steering_angle))
        actual_steer = self.vehicle.state.steering_angle + d_steer

        # 5. DRS activation in track DRS zones when within 1.0s of car ahead (or solo/practice)
        in_drs = False
        if hasattr(self.track, "is_in_drs_zone"):
            in_drs = bool(self.track.is_in_drs_zone(s_mod))
        gap_sec = (lead_gap_m / max(10.0, v_curr)) if (lead_gap_m is not None and lead_gap_m > 0.0) else 0.5
        drs_want = (
            in_drs
            and cmd_brake <= 0.01
            and abs(actual_steer) < 0.12
            and gap_sec < 1.0
            and self.calibration.drs_usage_probability >= 0.25
        )
        self.vehicle.drs_available = in_drs and (gap_sec < 1.0)
        self.vehicle.drs_active = drs_want

        # 6. Gearbox management supporting Gear 1 for sharp hairpins
        if self.vehicle.rpm >= RPM_AUTO_UPSHIFT and self.vehicle.gear < 8:
            self.vehicle.shift_up()
        elif (
            (self.vehicle.rpm <= 8200.0 and self.vehicle.gear > 2 and cmd_brake > 0.05)
            or (self.vehicle.speed_kmh < 55.0 and self.vehicle.gear > 1)
        ):
            self.vehicle.shift_down()

        # 7. Step vehicle physics & update spline coordinates with calibrated tyre grip
        surface_mu = np.full(4, self.calibration.grip_utilization, dtype=np.float64)
        self.vehicle.step(
            throttle=cmd_throttle,
            brake=cmd_brake,
            steer=actual_steer,
            dt=dt,
            drs_active=drs_want,
            surface_mu=surface_mu,
        )
        ds = self.vehicle.vx * dt
        self.s += ds
        self.total_distance_m += ds
        # Smoothly relax lateral offset d toward lateral_target
        self.d += (lateral_target - self.d) * min(1.0, dt * 3.5)

        # Synchronize world pose for OBB SAT queries
        if hasattr(self.track, "get_spline_point"):
            try:
                pos, tan, norm = self.track.get_spline_point(s_mod)
                yaw = self.track.spline.get_heading(s_mod) if hasattr(self.track, "spline") else math.atan2(float(tan[1]), float(tan[0]))
                self.vehicle.state.x = float(pos[0] + self.d * norm[0])
                self.vehicle.state.y = float(pos[1] + self.d * norm[1])
                self.vehicle.state.z = float(pos[2])
                self.vehicle.state.yaw = float(yaw)
            except Exception:
                pass

        # 8. Lap counter & timing
        calc_lap = int(max(0.0, self.total_distance_m) // track_len) + 1
        if calc_lap > self.lap and not self.finished:
            lap_dur = max(0.1, float(sim_time) - self.current_lap_start_time)
            self.lap_times.append(lap_dur)
            self.current_lap_start_time = float(sim_time)
            self.lap = min(total_laps, calc_lap)

        if self.total_distance_m >= track_len * total_laps and not self.finished:
            self.finished = True
            self.total_race_time = float(sim_time)

        self.last_output = AICarControlOutput(
            throttle=float(cmd_throttle),
            brake=float(cmd_brake),
            steer_rad=float(actual_steer),
            drs_active=bool(self.vehicle.drs_active),
            target_speed_ms=float(v_target),
            lookahead_m=float(ld),
            ttc_sec=float(ttc_sec),
            lateral_target_m=float(lateral_target),
        )
        return self.last_output

